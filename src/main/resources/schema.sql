
CREATE TABLE product (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(80) NOT NULL UNIQUE,
    price DECIMAL(10, 2) NOT NULL,
    stock INT NOT NULL CHECK (stock >= 0)
);

CREATE TABLE customer (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(80) NOT NULL,
    email VARCHAR(120) NOT NULL UNIQUE
);

-- H2 2.4: a CHECK with IN (...) or OR breaks once the connection that created the table is
-- closed ("Check constraint invalid"). The CASE form is equivalent and keeps working.
-- The PostgreSQL schema (db/postgresql/schema.sql) uses the plain IN form.
CREATE TABLE orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES customer(id),
    status VARCHAR(10) NOT NULL CHECK (CASE status WHEN 'NEW' THEN TRUE WHEN 'PAID' THEN TRUE
                                                   WHEN 'CANCELLED' THEN TRUE ELSE FALSE END),
    placed_at TIMESTAMP WITH TIME ZONE NOT NULL,
    total DECIMAL(12, 2) NOT NULL
);

CREATE INDEX orders_customer_idx ON orders(customer_id, placed_at);

CREATE TABLE order_line (
    order_id BIGINT NOT NULL REFERENCES orders(id),
    product_id BIGINT NOT NULL REFERENCES product(id),
    qty INT NOT NULL CHECK (qty >= 1),
    unit_price DECIMAL(10, 2) NOT NULL,
    PRIMARY KEY (order_id, product_id)
);
